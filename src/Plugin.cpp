// =============================================================================
//  SanguinesTrade SKSE Plugin -- Prisma UI bridge
// =============================================================================
//  A thin native bridge between Papyrus and PrismaUI. Exposes a small set of
//  global functions on the Papyrus class "ST_PrismaBridge" and translates
//  JavaScript button clicks (window.STAction(payload)) into a Papyrus mod
//  event "ST_PrismaAction" that ST_LedgerMenu listens for.
//
//  All UI state is owned by the HTML/JS view. The plugin only:
//    1. Creates / shows / focuses / hides the Prisma view
//    2. Forwards arbitrary JS strings into the view (Invoke)
//    3. Forwards JS callbacks back out to Papyrus as mod events
//
//  Plugin metadata (name, version) is auto-generated by the
//  add_commonlibsse_plugin CMake macro from PROJECT_NAME / PROJECT_VERSION
//  in CMakeLists.txt. Do not declare SKSEPluginInfo or SKSEPlugin_Version
//  in this file -- doing so creates duplicate symbol errors at link time.
// =============================================================================

#include "PCH.h"

namespace {

    // -------------------------------------------------------------------------
    //  Configuration
    // -------------------------------------------------------------------------
    constexpr auto kViewPath        = "SanguinesTrade/index.html";  // relative to Data/PrismaUI/views/
    constexpr auto kJSListenerName  = "STAction";                   // JS calls window.STAction(payload)
    constexpr auto kModEventName    = "ST_PrismaAction";            // Papyrus listens for this
    constexpr auto kPapyrusClass    = "ST_PrismaBridge";            // ScriptName on the Papyrus side
    constexpr auto kLogFileName     = "SanguinesTrade.log";

    // -------------------------------------------------------------------------
    //  Plugin state
    // -------------------------------------------------------------------------
    PRISMA_UI_API::IVPrismaUI1* g_prisma   = nullptr;
    PrismaView                  g_view     = 0;
    std::atomic<bool>           g_domReady = false;

    // -------------------------------------------------------------------------
    //  JS -> Papyrus bridge: send mod event when window.STAction(payload) fires
    // -------------------------------------------------------------------------
    void OnJSAction(const char* a_payload)
    {
        if (!a_payload) return;

        // Copy the payload onto a new string. The pointer Prisma hands us is
        // not guaranteed to live past this callback, and we need to defer the
        // mod-event send onto the main thread.
        std::string payload = a_payload;

        SKSE::GetTaskInterface()->AddTask([payload]() {
            auto* source = SKSE::GetModCallbackEventSource();
            if (!source) {
                spdlog::error("ModCallbackEventSource unavailable; dropping action");
                return;
            }

            SKSE::ModCallbackEvent ev;
            ev.eventName = kModEventName;
            ev.strArg    = payload;
            ev.numArg    = 0.0f;
            ev.sender    = nullptr;

            source->SendEvent(&ev);
            spdlog::info("Dispatched ST_PrismaAction: {}", payload);
        });
    }

    // -------------------------------------------------------------------------
    //  DOM-ready callback: just flips the ready flag. JS listener registration
    //  happens earlier (right after CreateView) so it's not lost if DOM-ready
    //  fails to fire on a broken HTML file.
    // -------------------------------------------------------------------------
    void OnDomReady(PrismaView a_view)
    {
        spdlog::info("View DOM ready (view={})", a_view);
        g_domReady.store(true, std::memory_order_release);
    }

    // -------------------------------------------------------------------------
    //  Lazy view creation -- safe to call repeatedly
    // -------------------------------------------------------------------------
    bool EnsureView()
    {
        if (!g_prisma) {
            spdlog::warn("EnsureView: PrismaUI API not available");
            return false;
        }

        if (g_view && g_prisma->IsValid(g_view)) {
            return true;
        }

        // Recreating from scratch -- reset readiness flag
        g_domReady.store(false, std::memory_order_release);

        spdlog::info("Creating view: {}", kViewPath);
        g_view = g_prisma->CreateView(kViewPath, OnDomReady);

        if (!g_view) {
            spdlog::error("CreateView returned 0 -- check that {} exists under Data/PrismaUI/views/", kViewPath);
            return false;
        }

        // Register JS listener immediately. Listeners bind to the view object,
        // not the DOM, so this works before DOM-ready and survives across
        // navigations within the view.
        g_prisma->RegisterJSListener(g_view, kJSListenerName, OnJSAction);
        spdlog::info("Registered JS listener: window.{}", kJSListenerName);

        return true;
    }

    // =========================================================================
    //  Papyrus natives
    //  All functions are global and live on class kPapyrusClass.
    // =========================================================================

    bool Papyrus_IsAvailable(RE::StaticFunctionTag*)
    {
        return g_prisma != nullptr;
    }

    bool Papyrus_PreloadView(RE::StaticFunctionTag*)
    {
        return EnsureView();
    }

    // Engine-level pause via RE::Main::freezeTime. This freezes time-of-day,
    // actor AI, projectiles, scripts -- everything -- without engaging
    // Skyrim's paused-menu pipeline. That's the critical distinction: the
    // menu-pause path that Prisma's Focus(pauseGame=true) goes through
    // hides the HUD as a coupled side effect we can't turn off. freezeTime
    // is a separate engine-level bool that just stops the simulation tick.
    //
    // Reference: Steve Townsend's PauseAfterLoadUnscripted does exactly
    // this on load-screen close. Same mechanism, different trigger.
    void SetEnginePause(bool a_paused)
    {
        auto* main = RE::Main::GetSingleton();
        if (!main) return;
        main->GetRuntimeData().freezeTime = a_paused; // SKSE-Hotfixes: NG 11 moved freezeTime into Main::RUNTIME_DATA (RE/M/Main.h:94)
    }

    // Strip the menu-pause and freeze-frame-background flags from Prisma's
    // PrismaUI_FocusMenu. Skyrim's menu pipeline keys HUD suppression off
    // these flags being set on whichever menu is currently focused, so
    // clearing them keeps the HUD visible while the Ledger is up. We
    // pause the world ourselves via RE::Main::freezeTime so dropping the
    // menu's pause flag doesn't actually unpause anything.
    //
    // Reference: Skyrim Souls SE applies the same flag-strip technique
    // (Hooks.cpp, CreateGameMenuInstance) at menu construction. We do it
    // post-Focus instead because we don't control the constructor.
    //
    // Bit values per CommonLibSSE-NG UI_MENU_FLAGS:
    //   kPausesGame            = bit 0 (1 << 0)  -- HUD-hide trigger
    //   kFreezeFrameBackground = bit 5 (1 << 5)  -- captures world frame as bg
    //   (Skyrim Souls SE calls these kFlag_PauseGame and kFlag_StopDrawingWorld
    //    respectively; same bits, different historical names.)
    void StripPrismaMenuFlags()
    {
        auto* ui = RE::UI::GetSingleton();
        if (!ui) return;
        static const RE::BSFixedString kPrismaFocusMenu{ "PrismaUI_FocusMenu" };
        auto menu = ui->GetMenu(kPrismaFocusMenu);
        if (!menu) {
            spdlog::warn("StripPrismaMenuFlags: PrismaUI_FocusMenu not found");
            return;
        }
        menu->menuFlags.reset(RE::UI_MENU_FLAGS::kPausesGame);
        menu->menuFlags.reset(RE::UI_MENU_FLAGS::kFreezeFrameBackground);
        spdlog::info("StripPrismaMenuFlags: cleared kPausesGame and kFreezeFrameBackground on PrismaUI_FocusMenu");
    }

    // Force the HUD menu visible by enqueuing a kShow message. Safe to
    // call repeatedly; no-op when HUD is already visible.
    void ForceHUDShow()
    {
        auto* msgQueue = RE::UIMessageQueue::GetSingleton();
        if (!msgQueue) return;
        static const RE::BSFixedString kHudMenuName{ "HUD Menu" };
        msgQueue->AddMessage(kHudMenuName, RE::UI_MESSAGE_TYPE::kShow, nullptr);
    }

    bool Papyrus_OpenLedger(RE::StaticFunctionTag*)
    {
        if (!EnsureView()) return false;
        g_prisma->Show(g_view);
        // Focus WITHOUT Prisma's pauseGame. Prisma's pause mechanism couples
        // to Skyrim's paused-menu pipeline which hides the HUD; we instead
        // pause the engine ourselves below via freezeTime, which doesn't.
        g_prisma->Focus(g_view);
        SetEnginePause(true);
        // Strip the HUD-suppressing flags from Prisma's PrismaUI_FocusMenu
        // on the next task tick. Deferring lets Skyrim's menu manager
        // finish registering the menu before we look it up. Without this
        // strip, even with no Prisma pause, the HUD hides on certain
        // close paths because the menu still has kFlag_PauseGame set.
        SKSE::GetTaskInterface()->AddTask([]() {
            StripPrismaMenuFlags();
        });
        spdlog::info("OpenLedger: shown, focused, engine pause set, flag-strip queued");
        return true;
    }

    void Papyrus_CloseLedger(RE::StaticFunctionTag*)
    {
        if (!g_prisma || !g_view) return;
        // Order:
        //  1. Unfocus immediately so input goes back to the player.
        //  2. Defer Hide+unpause one task tick so Prisma's focus-release
        //     plumbing has a chance to settle.
        //  3. Force HUD visible after the hide as belt-and-suspenders.
        g_prisma->Unfocus(g_view);
        SKSE::GetTaskInterface()->AddTask([]() {
            if (!g_prisma || !g_view) return;
            g_prisma->Hide(g_view);
            SetEnginePause(false);
            ForceHUDShow();
            spdlog::info("CloseLedger (deferred): hidden, pause cleared, HUD restored");
        });
        spdlog::info("CloseLedger: unfocused, deferred close queued");
    }

    bool Papyrus_IsOpen(RE::StaticFunctionTag*)
    {
        if (!g_prisma || !g_view) return false;
        return !g_prisma->IsHidden(g_view) && g_prisma->HasFocus(g_view);
    }

    bool Papyrus_IsDomReady(RE::StaticFunctionTag*)
    {
        return g_domReady.load(std::memory_order_acquire);
    }

    void Papyrus_Invoke(RE::StaticFunctionTag*, std::string a_jsCode)
    {
        // CRITICAL: this parameter MUST be std::string, not RE::BSFixedString.
        // BSFixedString is Skyrim's case-insensitive interned string pool --
        // any string passed through it gets case-folded to match existing
        // pool entries. That destroys JSON ("true" -> "True", "venues" ->
        // "Venues") and makes the snapshot unparseable as a JS literal.
        // std::string passes the raw bytes through unchanged.
        if (!g_prisma || !g_view) {
            spdlog::warn("Invoke called with no view");
            return;
        }
        if (!g_domReady.load(std::memory_order_acquire)) {
            spdlog::warn("Invoke called before DOM ready -- queue your call after IsDomReady()");
        }
        g_prisma->Invoke(g_view, a_jsCode.c_str(), nullptr);
    }

    bool RegisterPapyrus(RE::BSScript::IVirtualMachine* a_vm)
    {
        a_vm->RegisterFunction("IsAvailable", kPapyrusClass, Papyrus_IsAvailable);
        a_vm->RegisterFunction("PreloadView", kPapyrusClass, Papyrus_PreloadView);
        a_vm->RegisterFunction("OpenLedger",  kPapyrusClass, Papyrus_OpenLedger);
        a_vm->RegisterFunction("CloseLedger", kPapyrusClass, Papyrus_CloseLedger);
        a_vm->RegisterFunction("IsOpen",      kPapyrusClass, Papyrus_IsOpen);
        a_vm->RegisterFunction("IsDomReady",  kPapyrusClass, Papyrus_IsDomReady);
        a_vm->RegisterFunction("Invoke",      kPapyrusClass, Papyrus_Invoke);
        spdlog::info("Registered 7 Papyrus natives on {}", kPapyrusClass);
        return true;
    }

    // =========================================================================
    //  SKSE messaging hook
    // =========================================================================
    void OnSKSEMessage(SKSE::MessagingInterface::Message* a_msg)
    {
        if (!a_msg) return;

        switch (a_msg->type) {
            case SKSE::MessagingInterface::kPostLoad:
            {
                // Per Prisma docs, request the API at or after kPostLoad so the
                // PrismaUI DLL has finished initializing.
                g_prisma = static_cast<PRISMA_UI_API::IVPrismaUI1*>(
                    PRISMA_UI_API::RequestPluginAPI(PRISMA_UI_API::InterfaceVersion::V1));

                if (g_prisma) {
                    spdlog::info("PrismaUI API obtained (V1)");
                } else {
                    spdlog::error("PrismaUI not loaded -- bridge will be inert. "
                                  "Confirm PrismaUI.dll is in Data/SKSE/Plugins/");
                }
                break;
            }

            case SKSE::MessagingInterface::kDataLoaded:
            {
                // Pre-create the view (hidden) so the first OpenLedger call
                // is fast. CreateView at this point has the data files loaded
                // and the renderer is ready.
                if (g_prisma && EnsureView()) {
                    g_prisma->Hide(g_view);
                    spdlog::info("View pre-loaded and hidden");
                }
                break;
            }

            default:
                break;
        }
    }

    // -------------------------------------------------------------------------
    //  Logging setup
    // -------------------------------------------------------------------------
    void InitLogging()
    {
        auto folder = SKSE::log::log_directory();
        if (!folder) return;

        auto path = *folder / kLogFileName;
        auto sink = std::make_shared<spdlog::sinks::basic_file_sink_mt>(path.string(), /*truncate=*/true);
        auto log  = std::make_shared<spdlog::logger>("global", std::move(sink));

        log->set_level(spdlog::level::info);
        log->flush_on(spdlog::level::info);

        spdlog::set_default_logger(std::move(log));
        spdlog::set_pattern("[%H:%M:%S.%e] [%l] %v");
    }

}  // namespace

// =============================================================================
//  SKSE plugin entry point
//  add_commonlibsse_plugin auto-generates SKSEPlugin_Query and
//  SKSEPlugin_Version from CMakeLists.txt. We just provide the load function.
// =============================================================================

SKSEPluginLoad(const SKSE::LoadInterface* a_skse)
{
    SKSE::Init(a_skse);
    InitLogging();

    spdlog::info("===== SanguinesTrade Prisma bridge loading =====");
    spdlog::info("Plugin version 1.0.0");

    auto* messaging = SKSE::GetMessagingInterface();
    if (!messaging || !messaging->RegisterListener(OnSKSEMessage)) {
        spdlog::error("Failed to register SKSE message listener");
        return false;
    }

    auto* papyrus = SKSE::GetPapyrusInterface();
    if (!papyrus || !papyrus->Register(RegisterPapyrus)) {
        spdlog::error("Failed to register Papyrus natives");
        return false;
    }

    spdlog::info("Plugin load complete; awaiting kPostLoad");
    return true;
}
